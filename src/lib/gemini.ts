// --- Gemini lesson generator ----------------------------------------------
// Client-side call to the Gemini API for the personalized lessons demo.
// The API key ships in the browser bundle via VITE_GEMINI_API_KEY, which is
// fine for a local demo but must not be used once this app is deployed
// publicly (see PersonalizedLessons discussion) — move this behind a
// Firebase Cloud Function first if that happens.

import { GoogleGenerativeAI } from "@google/generative-ai";
import { loadCurriculum, retrieve, type CurriculumDoc } from "./curriculum";

export class LessonGenerationError extends Error {}
export class CurriculumSearchError extends Error {}

const apiKey = import.meta.env.VITE_GEMINI_API_KEY as string | undefined;

export type QuestionResults = Record<string, Record<string, boolean>>;

function buildPrompt(questions: QuestionResults): string {
    const lines = Object.entries(questions).map(([question, answerMap]) => {
        const [studentAnswer, wasCorrect] = Object.entries(answerMap)[0] ?? ["", false];
        return `- "${question}" — student answered "${studentAnswer}" (${wasCorrect ? "correct" : "incorrect"})`;
    });

    return [
        "You are creating a short, encouraging personalized lesson for a young child",
        "learning about fruits and vegetables, based on their quiz results below.",
        "Focus on the questions they got wrong, gently correct any misconceptions, ask a new question to reinforce learning,",
        "and keep it under 70 words in simple, friendly language. dont use * character or hearts unless necessary but food icons are lightly encouraged ",
        "",
        "Quiz results:",
        ...lines,
    ].join("\n");
}

export async function generatePersonalizedLesson(questions: QuestionResults): Promise<string> {
    if (!apiKey) {
        throw new LessonGenerationError(
            "Missing VITE_GEMINI_API_KEY. Add it to a .env file to enable lesson generation."
        );
    }

    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: "gemini-3.5-flash-lite" });

    try {
        const result = await model.generateContent(buildPrompt(questions));
        return result.response.text();
    } catch (err) {
        throw new LessonGenerationError(
            err instanceof Error ? err.message : "Lesson generation failed."
        );
    }
}

// --- Curriculum search (copilot demo) --------------------------------------
// RAG over the verified curriculum in Firestore:
//   1. retrieve the top matching curriculum doc (see ./curriculum.ts)
//   2. pass it to Gemini as context, which may reword/format it
//   3. label the result "curriculum" if the answer was grounded in that doc,
//      or "ai" if nothing matched (or Gemini said the doc didn't answer it)
//
// Retrieval is simple keyword scoring over a cached copy of the collection,
// which is plenty for a few dozen docs. If the curriculum grows, swap
// `retrieve` for a vector search (Firestore vector index + embeddings) — the
// rest of this flow stays the same.
//
// Only the single best-ranked match is kept (see the `.slice(0, 1)` below) —
// this used to keep the top ~3, but a grounded answer only ever needs one
// good source, and it keeps the "Found in:" UI to one lesson instead of a
// list.
//
// Two reading levels come back on purpose: `teacherSummary` is prep-level
// context for the adult, `studentBullets` is what actually lands on the
// slide — short (5-10 words), present tense, K-6 vocabulary. The search
// result card is also reused as the "generate a slide from a topic" input,
// since both are really the same request: "tell me about X at both levels."

export interface CurriculumSearchResult {
    title: string;
    teacherSummary: string;
    studentBullets: string[];
    /** "curriculum" = grounded in a Firestore doc, "ai" = generated by Gemini alone */
    source: "curriculum" | "ai";
    /** Title of the curriculum doc used (empty when source is "ai") */
    sourceTitles: string[];
}

function buildSearchPrompt(query: string, hits: CurriculumDoc[]): string {
    const grounding =
        hits.length > 0
            ? [
                  "Answer using ONLY the curriculum excerpt below. You may reword and",
                  "format it for the teacher and for young students, but do not add facts",
                  "that are not in the excerpt. If the excerpt does not actually answer the",
                  'topic, ignore it, answer from general knowledge, and set "usedCurriculum" to false.',
                  "",
                  "CURRICULUM EXCERPT:",
                  ...hits.map(
                      (d, i) =>
                          `[${i + 1}] ${d.title} (${d.subject}, grades ${d.gradeLevel}): ${d.content}`
                  ),
              ]
            : [
                  "No curriculum excerpt matched this topic. Answer from general knowledge",
                  'and set "usedCurriculum" to false.',
              ];

    return [
        "You are helping a K-6 teacher prep a lesson from a fruits-and-vegetables",
        "curriculum. Given the topic or question below, respond with ONLY valid JSON",
        "(no markdown fences, no extra text) in exactly this shape:",
        '{"title": "...", "teacherSummary": "...", "studentBullets": ["...", "..."], "usedCurriculum": true}',
        "",
        "- title: short topic title, under 8 words.",
        "- teacherSummary: 2-3 sentences of prep context, written for the teacher.",
        "- studentBullets: 3-5 bullet points a K-6 student could read or hear aloud.",
        "  Each bullet is 5-10 words, present tense, simple everyday vocabulary,",
        "  no jargon, one idea per bullet — this is what goes on the slide.",
        '- usedCurriculum: true only if your answer is based on the curriculum excerpt.',
        "",
        ...grounding,
        "",
        `Topic: "${query}"`,
    ].join("\n");
}

function parseSearchResponse(
    rawText: string,
    fallbackQuery: string,
    hits: CurriculumDoc[]
): CurriculumSearchResult {
    const cleaned = rawText.trim().replace(/^```json\s*|^```\s*|```$/g, "").trim();

    try {
        const parsed = JSON.parse(cleaned);
        if (
            typeof parsed.title === "string" &&
            typeof parsed.teacherSummary === "string" &&
            Array.isArray(parsed.studentBullets)
        ) {
            // Only claim "curriculum" if a doc was actually retrieved AND the
            // model says it used it.
            const fromCurriculum = hits.length > 0 && parsed.usedCurriculum === true;

            return {
                title: parsed.title,
                teacherSummary: parsed.teacherSummary,
                studentBullets: parsed.studentBullets.filter(
                    (b: unknown): b is string => typeof b === "string"
                ),
                source: fromCurriculum ? "curriculum" : "ai",
                sourceTitles: fromCurriculum ? hits.slice(0, 1).map((h) => h.title) : [],
            };
        }
    } catch {
        // fall through — the model didn't return valid JSON this time
    }

    // Best-effort fallback so the feature still works even if the model
    // ignores the JSON instruction: use the raw text as the teacher summary
    // and naively split it into bullets (not guaranteed to be kid-level).
    // We can't tell whether the doc was used here, so label it "ai".
    return {
        title: fallbackQuery,
        teacherSummary: cleaned,
        studentBullets: cleaned
            .split(/(?<=[.!?])\s+/)
            .map((s) => s.trim())
            .filter(Boolean)
            .slice(0, 5),
        source: "ai",
        sourceTitles: [],
    };
}

export async function searchCurriculum(query: string): Promise<CurriculumSearchResult> {
    if (!apiKey) {
        throw new CurriculumSearchError(
            "Missing VITE_GEMINI_API_KEY. Add it to a .env file to enable search."
        );
    }

    // Retrieve from Firestore. If that fails (offline, security rules, etc.),
    // fall back to plain AI generation rather than breaking search.
    // Only keep the single best-ranked match — `retrieve` returns hits sorted
    // by score, so slicing to 1 here is what drives sourceTitles down to one
    // lesson instead of the top ~3.
    let hits: CurriculumDoc[] = [];
    try {
        hits = retrieve(query, await loadCurriculum()).slice(0, 1);
    } catch (err) {
        console.warn("Curriculum lookup failed, falling back to AI only", err);
    }

    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({
        model: "gemini-3.5-flash-lite",
        generationConfig: { responseMimeType: "application/json" },
    });

    try {
        const result = await model.generateContent(buildSearchPrompt(query, hits));
        return parseSearchResponse(result.response.text(), query, hits);
    } catch (err) {
        throw new CurriculumSearchError(
            err instanceof Error ? err.message : "Curriculum search failed."
        );
    }
}

// --- Fact of the day (copilot demo) -----------------------------------
// Replaces the old static FACTS_OF_THE_DAY array: picks a curriculum doc
// from Firestore (deterministically by day, or randomly on refresh) and
// condenses it into a single kid-friendly fact via Gemini. Falls back to
// the raw doc content if the model call fails or no API key is set, so the
// feature degrades gracefully rather than breaking.

export interface FactOfTheDay {
    text: string;
    /** Title of the curriculum doc the fact was drawn from */
    source: string;
}

export async function getFactOfTheDay(
    mode: "daily" | "random" = "daily",
    excludeTitle?: string
): Promise<FactOfTheDay> {
    let docs: CurriculumDoc[];
    try {
        docs = await loadCurriculum();
    } catch (err) {
        throw new CurriculumSearchError(
            err instanceof Error ? err.message : "Could not load curriculum."
        );
    }

    if (docs.length === 0) {
        throw new CurriculumSearchError("No curriculum docs available.");
    }

    let pool = docs;
    if (mode === "random" && excludeTitle && docs.length > 1) {
        pool = docs.filter((d) => d.title !== excludeTitle);
    }

    const index =
        mode === "daily"
            ? Math.floor(Date.now() / (1000 * 60 * 60 * 24)) % pool.length
            : Math.floor(Math.random() * pool.length);

    const doc = pool[index];

    if (!apiKey) {
        return { text: doc.content, source: doc.title };
    }

    try {
        const genAI = new GoogleGenerativeAI(apiKey);
        const model = genAI.getGenerativeModel({ model: "gemini-3.5-flash-lite" });
        const prompt = [
            "Extract ONE single fun, surprising fact for kids from the curriculum",
            "excerpt below. One sentence, under 25 words, no preamble, no quotes,",
            "no markdown.",
            "",
            `Excerpt (${doc.title}): ${doc.content}`,
        ].join("\n");

        const result = await model.generateContent(prompt);
        const text = result.response.text().trim();
        return { text: text || doc.content, source: doc.title };
    } catch {
        // Degrade to raw content rather than surfacing an error for what's
        // meant to be a lightweight sidebar feature.
        return { text: doc.content, source: doc.title };
    }
}

// --- Parent copilot: home activities ---------------------------------------
// Same RAG flow as searchCurriculum, but the output is aimed at a parent:
// what the child is learning, one activity to do at home, conversation
// starters, and an optional nutrition tie-in.

export interface HomeActivityResult {
    title: string;
    learningBlurb: string;
    activity: {
        name: string;
        time: string;
        materials: string[];
        steps: string[];
    };
    conversationStarters: string[];
    /** Empty string when a nutrition tie-in doesn't fit the topic */
    nutritionTip: string;
    source: "curriculum" | "ai";
    sourceTitles: string[];
}

function buildParentPrompt(query: string, hits: CurriculumDoc[]): string {
    const grounding =
        hits.length > 0
            ? [
                  "Facts about fruits and vegetables must come ONLY from the curriculum",
                  "excerpt below (the activity itself can be your own idea, but don't add",
                  "new facts). If the excerpt does not actually relate to the topic, ignore",
                  'it, use general knowledge, and set "usedCurriculum" to false.',
                  "",
                  "CURRICULUM EXCERPT:",
                  ...hits.map(
                      (d, i) =>
                          `[${i + 1}] ${d.title} (${d.subject}, grades ${d.gradeLevel}): ${d.content}`
                  ),
              ]
            : [
                  "No curriculum excerpt matched this topic. Use general knowledge",
                  'and set "usedCurriculum" to false.',
              ];

    return [
        "You are helping a busy parent bring their K-6 child's fruits-and-vegetables",
        "learning into the home. Given the topic or question below, respond with ONLY",
        "valid JSON (no markdown fences, no extra text) in exactly this shape:",
        '{"title": "...", "learningBlurb": "...", "activity": {"name": "...", "time": "...", "materials": ["..."], "steps": ["..."]}, "conversationStarters": ["..."], "nutritionTip": "...", "usedCurriculum": true}',
        "",
        "- title: short topic title, under 8 words.",
        "- learningBlurb: 1-2 sentences on what the child is learning, plain language, no jargon.",
        '- activity: ONE simple home activity. "time" like "15 minutes". 2-5 common household',
        "  materials, 3-5 short steps. No special equipment. Mention adult supervision if",
        "  knives or heat are involved.",
        "- conversationStarters: 2-3 open-ended questions to ask at dinner or in the car.",
        "- nutritionTip: ONE sentence connecting the topic to eating or trying the food",
        "  at home. Use an empty string if it doesn't fit naturally.",
        "- usedCurriculum: true only if your answer is based on the curriculum excerpt.",
        "",
        ...grounding,
        "",
        `Topic: "${query}"`,
    ].join("\n");
}

function stringList(v: unknown): string[] {
    return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];
}

export async function searchHomeActivities(query: string): Promise<HomeActivityResult> {
    if (!apiKey) {
        throw new CurriculumSearchError(
            "Missing VITE_GEMINI_API_KEY. Add it to a .env file to enable search."
        );
    }

    let hits: CurriculumDoc[] = [];
    try {
        hits = retrieve(query, await loadCurriculum()).slice(0, 1);
    } catch (err) {
        console.warn("Curriculum lookup failed, falling back to AI only", err);
    }

    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({
        model: "gemini-3.5-flash-lite",
        generationConfig: { responseMimeType: "application/json" },
    });

    let rawText: string;
    try {
        const result = await model.generateContent(buildParentPrompt(query, hits));
        rawText = result.response.text();
    } catch (err) {
        throw new CurriculumSearchError(
            err instanceof Error ? err.message : "Activity search failed."
        );
    }

    try {
        const cleaned = rawText.trim().replace(/^```json\s*|^```\s*|```$/g, "").trim();
        const p = JSON.parse(cleaned);

        if (
            typeof p.title === "string" &&
            typeof p.learningBlurb === "string" &&
            typeof p.activity?.name === "string"
        ) {
            const fromCurriculum = hits.length > 0 && p.usedCurriculum === true;
            return {
                title: p.title,
                learningBlurb: p.learningBlurb,
                activity: {
                    name: p.activity.name,
                    time: typeof p.activity.time === "string" ? p.activity.time : "",
                    materials: stringList(p.activity.materials),
                    steps: stringList(p.activity.steps),
                },
                conversationStarters: stringList(p.conversationStarters),
                nutritionTip: typeof p.nutritionTip === "string" ? p.nutritionTip : "",
                source: fromCurriculum ? "curriculum" : "ai",
                sourceTitles: fromCurriculum ? hits.map((h) => h.title) : [],
            };
        }
    } catch {
        // fall through to the error below
    }

    throw new CurriculumSearchError("Couldn't read that response. Try again.");
}

